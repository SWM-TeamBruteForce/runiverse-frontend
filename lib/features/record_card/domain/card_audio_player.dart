/// 곡 하나를 틀어 주는 것.
///
/// ## ⚠️ 인터페이스로 가리는 이유
///
/// 테스트가 진짜 소리를 내면 안 된다. 구현(`JustAudioPlayer`)은 `data/`에
/// 있고, 여기는 **순수 Dart**다 — `domain/`에 오디오 패키지를 들이지 않는다
/// (CLAUDE.md).
///
/// ## ⚠️ 한 번에 한 곡이다
///
/// 카드 하나에 곡이 여럿이지만(기본곡 + 사진마다 하나) **보고 있는 장의
/// 곡만** 문다. 재생목록을 쓰지 않는 이유는 설계 5절에 있다.
abstract interface class CardAudioPlayer {
  /// [url]을 문다. 물려 있던 것은 버린다. **물기만 하고 틀지 않는다** —
  /// 장을 넘겼을 때 처음부터 나게 하는 길이다.
  ///
  /// ⚠️ 못 물면 **던진다.** 무엇 때문인지 가르지 않는다 — 안드로이드에서
  /// 올라오는 것은 ExoPlayer 오류라 HTTP 상태를 믿을 수 없다(설계 7-3).
  Future<void> load(String url);

  /// **지금 자리에서** 튼다. 멈췄다 다시 부르면 이어 듣는다.
  ///
  /// 곡이 끝나면 **그 곡을 반복한다.**
  ///
  /// ## ⚠️ 틀기 시작하면 끝난다
  ///
  /// 곡이 끝날 때까지 기다리지 **않는다.** 반복을 걸어 뒀으니 그것을 기다리면
  /// 영영 돌아오지 못하고, 부르는 쪽은 소리가 나기 시작한 것을 영영 모른다.
  Future<void> play();

  /// 멈춘다. 자리는 지킨다.
  Future<void> pause();

  /// 다른 앱이 지금 소리를 내고 있나. **자동 재생을 접을지 가르는 값이다** —
  /// 듣던 음악이 카드를 연다고 멈추면 안 된다(설계 3절 반목표).
  ///
  /// 안드로이드가 아니면 `false`다.
  Future<bool> otherAudioPlaying();

  Future<void> dispose();
}
