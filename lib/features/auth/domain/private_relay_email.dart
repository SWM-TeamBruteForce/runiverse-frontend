/// 애플 **"이메일 가리기"**가 만들어 준 주소인가.
///
/// 순수 Dart다. import가 하나도 없어 위젯 없이 테스트할 수 있다 — [EmailRule]과
/// 같은 자리에 둔다.
///
/// ## 왜 필요한가
///
/// 애플 로그인에서 가리기를 고른 사람의 계정 이메일은
/// `a1b2c3d4e5@privaterelay.appleid.com` 같은 **릴레이 주소**다. 애플이 앱마다
/// 다르게 만들어 주는 값이라, 설정 화면에 그대로 띄우면 사용자는 **처음 보는
/// 주소가 자기 계정에 박혀 있는 것**을 본다. 자기가 쓰는 주소도 아니고, 옮겨
/// 적어 쓸 수 있는 주소도 아니다.
///
/// ## 화면에서만 가린다
///
/// 서버·DB의 값은 그대로 둔다. 애플에 메일을 보낼 때 실제로 쓰이는 주소이고,
/// **가린 사람에게 이메일을 다시 입력받는 것은 애플이 권하지 않는다**(앱도
/// 이메일을 따로 받지 않는다).
abstract final class PrivateRelayEmail {
  /// 애플이 쓰는 릴레이 도메인. 하나뿐이다.
  static const domain = 'privaterelay.appleid.com';

  /// 대소문자를 가리지 않는다. 도메인은 원래 대소문자를 구분하지 않고,
  /// 서버가 받은 값을 그대로 돌려주므로 섞여 올 수 있다.
  static bool hides(String email) =>
      email.trim().toLowerCase().endsWith('@$domain');
}
