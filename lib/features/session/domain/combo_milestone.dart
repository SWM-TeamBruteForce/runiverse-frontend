/// 콤보가 어디서 한 번 울리는가.
///
/// ## ⚠️ 10초마다 울리지 않는다
///
/// 콤보가 오를 때마다 **틱**이 울린다(`party_provider.dart`). 눈금은 그보다
/// 성긴 자리에서 **크고 길게** 울리는 쪽이다 — **1 · 3 · 5 · 10, 그다음은
/// 10마다.**
///
/// 앞이 촘촘한 이유는 막 붙었을 때가 가장 궁금하기 때문이고, 뒤가 성겨도
/// 되는 이유는 **그 사이를 틱이 메우기 때문이다.** 틱이 없다면 100초 공백이
/// 되겠지만, 지금은 10초마다 작게 울린다.
///
/// ⚠️ **0은 눈금이 아니다.** 명세상 `comboCount`는 붙는 순간 `0`이다
/// (WS No 9). 거기서 크게 울리면 10초 뒤 눈금 `1`에서 연달아 두 번 크게
/// 떨린다. 붙는 순간은 틱으로 알린다.
library;

/// [count]가 지나온 **직전 눈금**. 콤보가 없으면 0이다.
///
/// ⚠️ **"지금 눈금인가"를 묻지 않는다.** 그렇게 두면 통지를 하나 놓치거나
/// 재연결로 콤보가 7에서 시작할 때 그 눈금이 영영 안 울린다.
int comboMilestoneOf(int count) {
  if (count < 1) return 0;
  if (count < 3) return 1;
  if (count < 5) return 3;
  if (count < 10) return 5;
  return count ~/ 10 * 10;
}

/// [before]에서 [after]로 가며 눈금을 넘었는가.
///
/// ⚠️ **건너뛰어도 한 번만 참이다.** 0에서 7로 뛰면 1·3·5를 몰아 울리는 것이
/// 아니라 한 번 울린다 — 세 번 떨리면 무슨 뜻인지 알 수 없다.
///
/// ⚠️ **최고 기록은 보지 않는다.** 끊겼다 다시 이어지면 1부터 다시 울린다.
/// 30m 경계에서 붙었다 떨어지기를 반복하는 사람에게 아무 말도 않으면, 정작
/// 붙어 있는 동안을 모른다.
bool comboMilestonePassed({required int before, required int after}) =>
    comboMilestoneOf(after) > comboMilestoneOf(before);
