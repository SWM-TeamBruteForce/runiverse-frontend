import 'dart:typed_data';

/// 올릴 수 있는 사진으로 바꾼다.
///
/// ## 왜 필요한가 — 세로 사진이 누워서 올라간다
///
/// 폰은 세로로 찍은 사진을 **가로 픽셀로 저장하고 EXIF에 회전 값만 남긴다.**
/// [ExifStripper]는 픽셀을 건드리지 않고 메타데이터만 들어내므로, 지우고 나면
/// **회전 값이 사라진 가로 사진**이 된다. 운영 S3의 파일이 8160×6120 가로에
/// EXIF가 없는 상태였던 것이 이것이다.
///
/// 그래서 **지우기 전에 회전을 픽셀에 적용해야 한다.** 순서가 뒤집히면 고쳐지지
/// 않는다.
///
/// ## 함께 줄인다
///
/// 원본(5.6MB · 8160×6120)을 그대로 올리면 88px 원 안에 띄울 때도 통째로
/// 디코딩한다 — 약 190MB다. 올리는 자리에서 줄여 두면 받는 쪽도 함께 가벼워진다.
///
/// ⚠️ **원본을 원래 크기로 펼친 뒤 줄이면 안 된다.** 그 190MB를 메모리가 적은
/// 폰에서 쓰면 앱이 멈춘다. 구현은 처음부터 목표 크기로 읽어 들여야 한다.
///
/// ## ⚠️ 메타데이터를 새 파일로 옮기지 않는다
///
/// 프로필 사진 URL은 인증 없이 공개라 촬영 위치가 그대로 나간다. 다시 저장할 때
/// EXIF를 그대로 붙이는 구현이 있어서([image_picker]의 `ExifDataCopier`가 GPS를
/// 복사한다), 여기 결과는 [ExifStripper]를 한 번 더 거쳐 보증한다.
abstract interface class ImageTransformer {
  /// [path]의 사진을 회전 적용·축소한 **JPEG 바이트**로 바꾼다.
  ///
  /// 알아보지 못한 형식이면 `null`이다. **원본을 그대로 쓰면 안 된다** —
  /// 회전도 위치 정보도 그대로 나간다.
  ///
  /// ## 짧은 변을 [shortEdge]에 맞춘다
  ///
  /// 긴 변이 아니라 짧은 변이다. 이 사진이 쓰이는 자리는 전부 **원으로 잘린
  /// 아바타**라, 잘려 나가지 않고 남는 것은 짧은 변이다. 긴 변을 맞추면 세로로
  /// 긴 사진에서 정작 보이는 부분이 뭉개진다.
  Future<Uint8List?> toUploadJpeg(String path, {int shortEdge, int quality});
}
