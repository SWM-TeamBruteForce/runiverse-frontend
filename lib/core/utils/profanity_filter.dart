/// 비속어를 `*`로 가린다. **표시할 때만 쓴다.**
///
/// ## ⚠️ 보내는 것을 막지 않는다
///
/// 보내는 쪽에서 막으면 **클라이언트를 고친 사람에게 아무 효력이 없다.** 반면
/// 여기처럼 **그리는 쪽에서** 가리면 상대가 무슨 앱을 쓰든 보는 사람이 보호된다.
/// 우회가 불가능한 자리는 이쪽이라 여기에만 걸었다.
///
/// 그래서 이 함수는 원문을 바꾸지 않는다. 저장된 메시지는 원문 그대로 남으므로
/// 나중에 신고 기능이 붙을 때 신고 대상을 그대로 넘길 수 있다.
///
/// ## 사전은 번들 + 우리 보강이다
///
/// 패키지가 들고 온 사전은 `시발`·`씨발`·`병신`·`fuck` 정도로 **매우 좁다.**
/// 대신 **정규화와 오탐 억제가 좋다** — 숫자·공백 우회를 접고, `시간`·`출발`
/// 같은 정상어를 지켜 준다. 그 엔진만 쓰고 단어는 [_addedWords]로 채운다.
/// [_addedWords]에 넣은 단어도 **정규화를 그대로 상속한다**(`좆1`, `니 애미`).
///
/// 패키지 코드는 MIT이지만 **사전 데이터는 별개다.** 일부 항목은 출처·라이선스가
/// 확인되지 않았고, 일부는 CC BY 4.0으로 저작자 표시 의무가 있다. 자세한 것은
/// 패키지의 `THIRD_PARTY_NOTICES.md`에 있다 — 고지 화면 숙제는 아직 남아 있다.
library;

import 'package:korean_profanity/korean_profanity.dart';

/// 번들이 못 잡아서 우리가 채운 것.
///
/// ## ⚠️ 여기에 단어를 넣기 전에
///
/// 1. **번들에 이미 있는 단어를 넣으면 생성자가 `ArgumentError`를 던진다.**
///    필터는 첫 메시지를 그릴 때 만들어지므로 **채팅 화면이 열리다 죽는다.**
///    `새끼`·`ㅅㅂ`·`ass`가 그런 경우라 여기 없다.
/// 2. `test/profanity_filter_test.dart`의 '가리지 않는다' 묶음을 **그 단어를
///    넣은 채로** 다시 돌린다. 오탐이 미탐보다 나쁘다.
///
/// ## 일부러 뺀 것 — 전부 오탐을 만들었다
///
/// | 뺀 것 | 깨지는 말 |
/// |---|---|
/// | `보지` `자지` | "지도 **보지** 못했어요", "아직 안 **자지**요" |
/// | `걸레` | 걸레는 청소 도구가 1차 의미다 |
/// | `미친` | "**미친** 속도네요"는 칭찬이다 |
/// | `꺼져` `죽어` | "힘들어 **죽어**요" |
/// | `cunt` | S**cunt**horpe |
/// | `dick` | **Dick**ens |
/// | `ㅗ` | **ㅗ**ㅜㅑ — 감탄 표현이 깨진다 |
///
/// 문구 확정은 디자인·운영 확인이 필요하다. 지금 목록은 **초안이다.**
const _addedWords = <String>[
  // 한국어
  '좆', '좇', '니애미', '니미', '느금마', '엠창',
  '개색기', '개세끼', '개색끼', '썅', '쌍놈', '지랄',
  '미친놈', '미친년', '등신', '쪼다', '창녀',
  '호모', '짱깨', '짱께', '씨팔', '시팔', '시벌', '씨벌',
  // 초성. 정상 한글 음절은 건드리지 않는다 — 'ㅅㄱ'·'ㅎㅎ'도 안전하다.
  'ㅄ', 'ㅈㄹ', 'ㅆㅂ', 'ㅂㅅ', 'ㅁㅊ', 'ㄳㄲ', 'ㅈㄴ',
  // 영어. 단어 경계는 패키지가 올바르게 지킨다(`class`·`assassin` 안전).
  'shit', 'shithead', 'asshole', 'bitch', 'bastard', 'fucking',
  'pussy', 'whore', 'slut', 'faggot', 'nigger', 'retard',
];

/// 번들이 **틀리게** 잡는 것.
///
/// `시발점`(始發點)은 번들 사전이 욕으로 본다. 러닝 앱에서 쓰는 말이라 끈다 —
/// 끄더라도 `시발`은 계속 잡힌다.
const _ignoreWords = <String>['시발점'];

/// 지워야 하는 보이지 않는 글자.
///
/// ## ⚠️ ZWJ(U+200D)는 빼고 지운다
///
/// 제로폭 공백을 글자 사이에 끼우면(`시​발`) 패키지 정규화를 **그냥
/// 통과한다.** 그래서 미리 걷어낸다.
///
/// 그런데 **ZWJ는 남겨야 한다.** `🏃‍♂️`는 ZWJ로 이어 붙인 한 글자라, 함께
/// 지우면 달리는 사람이 둘로 쪼개진다. 매일 보이는 손해가 드문 우회보다 크다.
/// 그 대가로 ZWJ를 끼우는 우회는 통한다 — 서버 필터가 생기면 그쪽이 막는다.
final _invisible = RegExp(r'[​‌⁠﻿­]');

/// 한 번만 만든다. 사전을 컴파일하는 비용이 있어 메시지마다 만들면 안 된다.
final _filter = KoreanProfanityFilter(
  addedWords: _addedWords,
  ignoreWords: _ignoreWords,
);

/// [text]에서 비속어를 `*`로 바꿔 돌려준다. 없으면 [text] 그대로다.
String maskProfanity(String text) {
  if (text.isEmpty) return text;
  return _filter.mask(text.replaceAll(_invisible, ''));
}
