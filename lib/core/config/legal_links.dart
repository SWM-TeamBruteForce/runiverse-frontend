/// 약관·개인정보처리방침 문서 주소.
///
/// ## ⚠️ 아직 정해지지 않았다
///
/// 문서가 준비되지 않았다. 가입 화면(S03)의 약관 동의도 링크 없이 체크박스만
/// 있고, `terms_agreement_page.dart`에 *"약관 전문 URL이 정해지면 여기 붙는다"*고
/// 자리만 남아 있다.
///
/// **비어 있는 동안 설정의 약관 행은 눌러도 "준비 중"이 뜬다.**
///
/// ## 주소가 정해지면
///
/// 여기를 채우고 **그때** `url_launcher`를 넣는다. 지금 패키지를 넣으면 열
/// URL이 없어 죽은 코드가 된다.
///
/// ## `AppConfig`에 두지 않은 이유
///
/// 시크릿이 아니고 빌드마다 달라지지도 않는다. `--dart-define`으로 넘기면
/// 넘기는 것을 잊었을 때 링크가 조용히 사라진다 — 그 편이 더 나쁘다.
abstract final class LegalLinks {
  /// 이용약관 전문.
  static const terms = '';

  /// 개인정보처리방침 전문.
  static const privacy = '';

  /// 열 수 있는가. 하나라도 비어 있으면 아직이다.
  ///
  /// 둘을 함께 보는 이유는 **설정 화면의 행이 하나**여서다. 약관만 있고
  /// 개인정보처리방침이 없으면 그 행은 절반만 지키지 못한 약속이 된다.
  static bool get isReady => terms.isNotEmpty && privacy.isNotEmpty;
}
